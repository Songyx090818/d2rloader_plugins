uint8_t* AllocateNear(uintptr_t anchor, size_t size) {
	SYSTEM_INFO info = {};
	GetSystemInfo(&info);
	const uintptr_t gran  = info.dwAllocationGranularity != 0 ? info.dwAllocationGranularity : 0x10000u;
	const uintptr_t start = anchor & ~(gran - 1);
	for (uintptr_t delta = gran; delta < 0x30000000ull; delta += gran) {
		const uintptr_t tries[2] = {start - delta, start + delta};
		for (uintptr_t candidate : tries) {
			if (candidate < 0x100000ull) continue;
			void* p = VirtualAlloc(reinterpret_cast<void*>(candidate), size, MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
			if (p != nullptr) return static_cast<uint8_t*>(p);
		}
	}
	return nullptr;
}

bool Rel32Fits(int64_t d) { return d >= INT32_MIN && d <= INT32_MAX; }

const char* StateName(State s) {
	switch (s) {
		case State::Applied:  return "applied";
		case State::Disabled: return "disabled";
		case State::Mismatch: return "byte-mismatch";
		case State::Failed:   return "write-failed";
		case State::NoRoom:   return "no-room";
		default:              return "pending";
	}
}

