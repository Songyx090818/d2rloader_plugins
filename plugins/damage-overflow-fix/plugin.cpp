constexpr uint32_t MaxWindowBytes = 512;

bool ApplySite(const D2RL::PluginContext* ctx, size_t index) {
	const Site& site = kSites[index];

	// Sized for the longest window in the table: srcdam_missile_scale replaces
	// 323 bytes. Up to 2.0.0 both buffers were 64 bytes, so that site was
	// rejected as a bad table entry and never installed.
	uint8_t expected[MaxWindowBytes];
	const uint32_t expectedSize = HexDecode(site.expectedHex, expected, sizeof(expected));
	if (expectedSize < 5) {
		g_state[index] = State::Failed;
		D2RL::LogErrorF(ctx, "[%s] bad expected-byte table entry", site.id);
		return false;
	}

	// A site another plugin already redirected starts with its jmp. That is not
	// a foreign build: critical-strike-damage, for one, owns deadly_strike_double
	// (0x44C3C8) and already does that doubling in 64 bits, saturated.
	if (expected[0] != 0xE9 && *reinterpret_cast<const uint8_t*>(ctx->exeBase + site.rva) == 0xE9) {
		g_state[index] = State::Disabled;
		D2RL::LogInfoF(ctx, "[%s] 0x%06X is already redirected by another plugin, site left to it", site.id, site.rva);
		return false;
	}

	if (!ctx->CheckExpectedBytes(site.rva, expected, expectedSize)) {
		g_state[index] = State::Mismatch;
		D2RL::LogWarnF(ctx, "[%s] bytes at 0x%06X are not what 3.3 should have, site skipped", site.id, site.rva);
		return false;
	}

	if (site.exitExpectedHex != nullptr) {
		uint8_t exitExpected[16];
		const uint32_t exitSize = HexDecode(site.exitExpectedHex, exitExpected, sizeof(exitExpected));
		if (exitSize == 0 || !ctx->CheckExpectedBytes(site.exitRva, exitExpected, exitSize)) {
			g_state[index] = State::Mismatch;
			D2RL::LogWarnF(ctx, "[%s] the rejoin target at 0x%06X is not what 3.3 should have, site skipped", site.id, site.exitRva);
			return false;
		}
	}

	if (g_dryRun) {
		g_state[index] = State::Applied;
		if (g_verbose) D2RL::LogInfoF(ctx, "[dry-run] %-22s 0x%06X -> 0x%06X  %s", site.id, site.rva, site.exitRva, site.doc);
		return true;
	}

	const uint32_t stubSize = HexLength(site.stubHex);
	if (g_used + stubSize + 5u + 16u > g_size) {
		g_state[index] = State::NoRoom;
		D2RL::LogErrorF(ctx, "[%s] trampoline block is full", site.id);
		return false;
	}

	uint8_t* const stub = g_block + g_used;
	if (HexDecode(site.stubHex, stub, static_cast<uint32_t>(g_size - g_used)) != stubSize) {
		g_state[index] = State::Failed;
		D2RL::LogErrorF(ctx, "[%s] bad stub table entry", site.id);
		return false;
	}

	// Point the four trace stores at this site's slot.
	for (int k = 0; k < 4; ++k) {
		if (site.traceAt[k] == 0) continue;   // this stub records nothing
		const uint64_t target = reinterpret_cast<uint64_t>(&g_slot[index].v[k]);
		memcpy(stub + site.traceAt[k], &target, sizeof(target));
	}

	// Point a call stub at the plugin function it is meant to reach.
	if (site.callAt != 0) {
		const uint64_t fn = reinterpret_cast<uint64_t>(&DmgOverflowStatWatch);
		memcpy(stub + site.callAt, &fn, sizeof(fn));
	}

	const uintptr_t exeBase = ctx->exeBase;
	uint8_t*        tail    = stub + stubSize;
	const int64_t   back    = static_cast<int64_t>(exeBase + site.exitRva) - static_cast<int64_t>(reinterpret_cast<uintptr_t>(tail) + 5);
	if (!Rel32Fits(back)) {
		g_state[index] = State::NoRoom;
		D2RL::LogErrorF(ctx, "[%s] rejoin jump is out of range", site.id);
		return false;
	}
	const int32_t backRel = static_cast<int32_t>(back);
	tail[0]               = 0xE9;
	memcpy(tail + 1, &backRel, sizeof(backRel));

	const int64_t out = static_cast<int64_t>(reinterpret_cast<uintptr_t>(stub)) - static_cast<int64_t>(exeBase + site.rva + 5);
	if (!Rel32Fits(out)) {
		g_state[index] = State::NoRoom;
		D2RL::LogErrorF(ctx, "[%s] stub is out of relative jump range", site.id);
		return false;
	}

	uint8_t patch[MaxWindowBytes];
	memset(patch, 0x90, sizeof(patch));
	const int32_t outRel = static_cast<int32_t>(out);
	patch[0]             = 0xE9;
	memcpy(patch + 1, &outRel, sizeof(outRel));

	if (!ctx->PatchBytes(site.rva, expected, expectedSize, patch, expectedSize)) {
		g_state[index] = State::Failed;
		D2RL::LogErrorF(ctx, "[%s] patch write failed at 0x%06X", site.id, site.rva);
		return false;
	}

	g_used += stubSize + 5u;
	while ((g_used & 15u) != 0 && g_used < g_size) g_block[g_used++] = 0xCC;

	g_state[index]  = State::Applied;
	g_stubVa[index] = reinterpret_cast<uintptr_t>(stub);
	if (g_verbose) D2RL::LogInfoF(ctx, "%-22s 0x%06X -> 0x%06X  %s", site.id, site.rva, site.exitRva, site.doc);
	return true;
}

