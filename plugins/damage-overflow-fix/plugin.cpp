extern "C" void DmgOverflowStatWatch(uint32_t statId, int32_t value, uint64_t statlist, uint64_t retAddr) noexcept {
	if (statId < kWatchFirstStat || statId > kWatchLastStat) return;
	WatchSlot& w = g_watch[statId - kWatchFirstStat];

	int32_t owner = -1;
	if (statlist > 0x10000ull) owner = *reinterpret_cast<const int32_t*>(statlist + 8);

	if (w.writes == 0) {
		w.maxValue = value; w.maxRet = retAddr; w.maxOwner = owner;
		w.minValue = value; w.minRet = retAddr; w.minOwner = owner;
	} else {
		if (value > w.maxValue) { w.maxValue = value; w.maxRet = retAddr; w.maxOwner = owner; }
		if (value < w.minValue) { w.minValue = value; w.minRet = retAddr; w.minOwner = owner; }
	}
	++w.writes;
	w.lastValue = value; w.lastRet = retAddr; w.lastOwner = owner;

	for (size_t i = 0; i < w.originCount; ++i) {
		if (w.origin[i].ret == retAddr) {
			++w.origin[i].hits;
			w.origin[i].lastValue = value;
			w.origin[i].ownerType = owner;
			return;
		}
	}
	if (w.originCount < kOriginSlots) {
		Origin& o   = w.origin[w.originCount++];
		o.ret       = retAddr;
		o.hits      = 1;
		o.lastValue = value;
		o.ownerType = owner;
	}
}

