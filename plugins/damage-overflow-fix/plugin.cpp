// damage_overflow_fix.cpp
//
// D2R 3.3 damage overflow fix. Port of the Eastern Sun Resurrected 2.4 set.
//
// D2R computes "value += value * percent / 100" (and "value * SrcDam / 128")
// through a compiler-emitted branch chain that does the multiply in 32 bits
// whenever both operands look small. Past INT32_MAX the product wraps negative,
// the negative result is folded back into the damage component, and the clamps
// further down the pipeline turn the hit into zero damage.
//
// Each site below is replaced by a jump into a stub generated at load time that
// does the same arithmetic in 64 bits and saturates to the int32 range. Because
// the game's own next instruction is usually "value = value + edx", the stubs
// saturate the SUM and hand back the delta that lands the game's add exactly on
// the saturated total. Saturating the delta alone is not enough: the 32-bit add
// of base plus a saturated delta wraps again.
//
// 2.4.0: missile_percent, the damage percent a missile applies to its own
// physical damage on impact (sub_140465420, 0x465A13) in 32 bits.
//
// 2.3.0: debug_log, a text file with every stage of every player hit and
// every player missile (stats, rolls, sites that ran, packets, resistance
// step, target), and the dmgoverflow log console command.
//
// 2.2.0: the melee kill check, the physical-to-element conversion add, and
// dmgoverflow hit, a per-hit report of every damage type at the resistance step.
//
// 2.1.0 (D2RLoader 1.3.1): the stat op group moved to D2RCore.dll, where the
// loader runs the stat engine (the game-image copy 2.0.2 patched is never
// called), and three groups were added: the resistance step, the hit's total
// life damage, and life/mana steal. See the TOML for every site.
//
// Every stub also records what it saw into a per-site trace slot, readable in
// game with the console command:
//
//   dmgoverflow            site list and state
//   dmgoverflow trace      last values observed at each site
//   dmgoverflow verify     ask D2RLoader's diagnostics service who owns each
//                          patched range, so a silent clobber by another
//                          plugin shows up instead of being guessed at
//
// Author: CelestialRayOne

