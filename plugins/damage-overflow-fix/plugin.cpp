int HexNibble(char c) {
	if (c >= '0' && c <= '9') return c - '0';
	if (c >= 'A' && c <= 'F') return c - 'A' + 10;
	if (c >= 'a' && c <= 'f') return c - 'a' + 10;
	return -1;
}

uint32_t HexDecode(const char* hex, uint8_t* out, uint32_t outSize) {
	uint32_t n = 0;
	for (const char* p = hex; p[0] != '\0' && p[1] != '\0'; p += 2) {
		const int hi = HexNibble(p[0]);
		const int lo = HexNibble(p[1]);
		if (hi < 0 || lo < 0 || n >= outSize) return 0;
		out[n++] = static_cast<uint8_t>((hi << 4) | lo);
	}
	return n;
}

uint32_t HexLength(const char* hex) { return static_cast<uint32_t>(strlen(hex) / 2); }

// ---------------------------------------------------------------------------
// minimal TOML reader: "key = true|false" and "key = [\"a\", \"b\"]"
// ---------------------------------------------------------------------------

const char* FindKey(const char* toml, const char* key) {
	const size_t len = strlen(key);
	for (const char* c = toml; *c != '\0'; ++c) {
		const bool lineStart = (c == toml) || c[-1] == '\n' || c[-1] == '\r';
		if (!lineStart) continue;
		const char* p = c;
		while (*p == ' ' || *p == '\t') ++p;
		if (strncmp(p, key, len) != 0) continue;
		const char* q = p + len;
		while (*q == ' ' || *q == '\t') ++q;
		if (*q != '=') continue;
		return q + 1;
	}
	return nullptr;
}

bool ReadBool(const char* toml, const char* key, bool fallback) {
	const char* v = FindKey(toml, key);
	if (v == nullptr) return fallback;
	while (*v == ' ' || *v == '\t') ++v;
	if (strncmp(v, "true", 4) == 0) return true;
	if (strncmp(v, "false", 5) == 0) return false;
	return fallback;
}

void ReadList(const char* toml, const char* key, char* out, size_t outSize) {
	out[0]          = '\0';
	const char* v   = FindKey(toml, key);
	if (v == nullptr) return;
	size_t n     = 0;
	bool   quote = false;
	for (const char* p = v; *p != '\0' && *p != '\n' && *p != ']'; ++p) {
		if (*p == '"') {
			if (quote && n + 1 < outSize) out[n++] = ',';
			quote = !quote;
			continue;
		}
		if (quote && n + 1 < outSize) out[n++] = *p;
	}
	out[n] = '\0';
}

bool ListHas(const char* list, const char* id) {
	if (list[0] == '\0') return false;
	char needle[96];
	snprintf(needle, sizeof(needle), "%s,", id);
	const size_t len = strlen(needle);
	for (const char* p = list; *p != '\0'; ++p) {
		const bool atStart = (p == list) || p[-1] == ',';
		if (atStart && strncmp(p, needle, len) == 0) return true;
	}
	return false;
}

bool GroupEnabled(const char* group) {
	for (size_t i = 0; i < kGroupCount; ++i) {
		if (strcmp(g_groups[i].name, group) == 0) return g_groups[i].enabled;
	}
	return false;
}


// ---------------------------------------------------------------------------
// stat write watch
//
// Hook at the entry of sub_1402F3030, the statlist stat setter. Every absolute
// value written to any stat on any unit passes through it, and the caller's
// return address is still at [rsp]. For stat ids 48..58 we record the value,
// the type of unit that owns the statlist, and who wrote it.
//
// D2RLoader 1.3.1 moved the setter into D2RCore (SetWideListStat): 0x2F3030 is
// now jmp [0x3E2A230] and four nops. The site takes those ten bytes and the
// stub rejoins at 0x2F7C00, the loader's other thunk through the same slot,
// so the write still reaches D2RCore with every register as the caller left
// it. The stub no longer replays a prologue: there is none left to replay.
//
// The unit type is the part that matters: the same stat id holds whole damage
// units on a player and 256ths on a missile, so a number that looks impossible
// on one is correct on the other.
// ---------------------------------------------------------------------------

