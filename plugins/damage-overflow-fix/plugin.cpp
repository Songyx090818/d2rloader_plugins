void Say(const D2RL::PluginContext* plugin, const char* format, ...) {
	char    line[512];
	va_list args;
	va_start(args, format);
	vsnprintf(line, sizeof(line), format, args);
	va_end(args);
	plugin->WriteConsoleMessage(line);
}

void ReportStatus(const D2RL::PluginContext* plugin) {
	int applied = 0;
	for (size_t i = 0; i < kSiteCount; ++i) {
		if (g_state[i] == State::Applied) ++applied;
	}
	Say(plugin, "damage-overflow-fix%s: %d of %zu sites active", g_dryRun ? " (dry run)" : "", applied, kSiteCount);
	for (size_t i = 0; i < kSiteCount; ++i) {
		Say(plugin, "  %-22s 0x%06X  %-13s  %s", kSites[i].id, kSites[i].rva, StateName(g_state[i]), kSites[i].group);
	}
}

void ReportTrace(const D2RL::PluginContext* plugin) {
	Say(plugin, "last values seen at each site (256ths, so divide by 256 for displayed damage)");
	bool any = false;
	for (size_t i = 0; i < kSiteCount; ++i) {
		if (g_state[i] != State::Applied) continue;
		const Slot& s = g_slot[i];
		if (s.v[0] == 0 && s.v[1] == 0 && s.v[2] == 0 && s.v[3] == 0) continue;
		any = true;
		const bool bad = (s.v[0] < 0) || (s.v[2] < 0) || (s.v[2] > 0x7FFFFFFFll) || (s.v[2] < -0x80000000ll);
		Say(plugin, "  %-22s %s=%lld  %s=%lld  %s=%lld  %s=%lld%s",
		    kSites[i].id,
		    kTraceLabel[0], static_cast<long long>(s.v[0]),
		    kTraceLabel[1], static_cast<long long>(s.v[1]),
		    kTraceLabel[2], static_cast<long long>(s.v[2]),
		    kTraceLabel[3], static_cast<long long>(s.v[3]),
		    bad ? "   <<< bad input or saturated" : "");
	}
	if (!any) Say(plugin, "  nothing recorded yet, land a hit first");
}

void ReportVerify(const D2RL::PluginContext* plugin) {
	const D2RL::DiagnosticsService* diag = nullptr;
	const D2RL::ServiceQueryResult    q    = plugin->QueryService(&diag);
	if (q != D2RL::ServiceQueryResult::Success || !D2RL::HasDiagnosticsServiceField(diag, D2RL::DiagnosticsServiceRequiredSize)) {
		Say(plugin, "diagnostics service unavailable on this D2RLoader build");
		return;
	}

	Say(plugin, "diagnostics: who owns each patched range");
	for (size_t i = 0; i < kSiteCount; ++i) {
		if (g_state[i] != State::Applied || g_dryRun) continue;

		uint8_t        expected[64];
		const uint32_t size = HexDecode(kSites[i].expectedHex, expected, sizeof(expected));

		D2RL::Diagnostics::HookQuery query = {};
		query.structSize   = D2RL::Diagnostics::HookQuerySize;
		query.rva          = kSites[i].rva;
		query.expected     = expected;
		query.expectedSize = size;

		D2RL::Diagnostics::HookStatus status = {};
		status.structSize                    = D2RL::Diagnostics::HookStatusSize;

		if (diag->queryHookStatus(plugin, &query, &status) != D2RL::Diagnostics::Result::Success) {
			Say(plugin, "  %-22s query failed", kSites[i].id);
			continue;
		}
		const char* state = "unchanged";
		if (status.state == D2RL::Diagnostics::ModificationState::Tracked) state = "tracked";
		if (status.state == D2RL::Diagnostics::ModificationState::Untracked) state = "UNTRACKED";
		Say(plugin, "  %-22s %-10s owners=%u %s", kSites[i].id, state, status.ownerCount,
		    status.ownerPluginId[0] != '\0' ? status.ownerPluginId : "");
	}
}


void SayAddr(const D2RL::PluginContext* plugin, const char* label, uint64_t ret, int32_t value, int32_t owner) {
	const uint64_t rva = ret - static_cast<uint64_t>(g_exeBase);
	if (rva < 0x4000000ull) {
		Say(plugin, "        %-5s %-12d on a %-8s written from RVA 0x%06X",
		    label, value, UnitTypeName(owner), static_cast<unsigned>(rva));
	} else {
		Say(plugin, "        %-5s %-12d on a %-8s written from OUTSIDE THE IMAGE at 0x%llX",
		    label, value, UnitTypeName(owner), static_cast<unsigned long long>(ret));
	}
}

void ReportStats(const D2RL::PluginContext* plugin) {
	Say(plugin, "absolute writes to the elemental damage-to-attacks stats");
	Say(plugin, "on a player these are whole units and cap at %d; on a missile they are 256ths", kShiftCeiling);
	bool any = false;
	for (size_t i = 0; i < kWatchCount; ++i) {
		const WatchSlot& w = g_watch[i];
		if (w.writes == 0) continue;
		any = true;
		Say(plugin, "  %-3zu %-13s writes=%u", kWatchFirstStat + i, kWatchName[i], w.writes);
		SayAddr(plugin, "max", w.maxRet, w.maxValue, w.maxOwner);
		SayAddr(plugin, "min", w.minRet, w.minValue, w.minOwner);
		SayAddr(plugin, "last", w.lastRet, w.lastValue, w.lastOwner);
		for (size_t k = 0; k < w.originCount; ++k) {
			const Origin&  o   = w.origin[k];
			const uint64_t rva = o.ret - static_cast<uint64_t>(g_exeBase);
			if (rva < 0x4000000ull) {
				Say(plugin, "        writer 0x%06X  x%u  last=%d on a %s",
				    static_cast<unsigned>(rva), o.hits, o.lastValue, UnitTypeName(o.ownerType));
			} else {
				Say(plugin, "        writer 0x%llX (outside the image)  x%u  last=%d on a %s",
				    static_cast<unsigned long long>(o.ret), o.hits, o.lastValue, UnitTypeName(o.ownerType));
			}
		}
	}
	if (!any) Say(plugin, "  nothing recorded yet; equip the gear or land a hit first");
}

void ResetStats(const D2RL::PluginContext* plugin) {
	memset(g_watch, 0, sizeof(g_watch));
	Say(plugin, "stat write watch cleared");
}

D2RL::ConsoleCommandResult OnCommand(D2R::Game::Client*, const D2RL::ConsoleCommandContext* cmd, void*) noexcept {
	if (cmd == nullptr || cmd->plugin == nullptr) return D2RL::ConsoleCommandResult::Failed;
	const char* args = (cmd->args != nullptr) ? cmd->args : "";
	while (*args == ' ') ++args;

	if (strncmp(args, "trace", 5) == 0) {
		ReportTrace(cmd->plugin);
	} else if (strncmp(args, "stats", 5) == 0) {
		ReportStats(cmd->plugin);
	} else if (strncmp(args, "reset", 5) == 0) {
		ResetStats(cmd->plugin);
	} else if (strncmp(args, "verify", 6) == 0) {
		ReportVerify(cmd->plugin);
	} else {
		ReportStatus(cmd->plugin);
		Say(cmd->plugin, "  try: dmgoverflow stats | trace | reset | verify");
	}
	return D2RL::ConsoleCommandResult::Handled;
}

